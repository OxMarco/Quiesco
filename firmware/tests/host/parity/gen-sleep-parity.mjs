// Regenerates sleep_parity_vectors.h from the app's own judgeMode
// (app/src/ui/sleep.ts), so the firmware's SleepSchedule is tested against
// the code it ports rather than against a second reading of it.
//
//   node tests/host/parity/gen-sleep-parity.mjs > tests/host/parity/sleep_parity_vectors.h
//
// Needs Node 22.18+ (type stripping). Each case runs the app in a child
// process under a fixed-offset time zone (no DST), which is what the
// firmware's single UTC offset models; the app rewrites the offset on every
// connect, which the "DST-like offset change" test covers separately.
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const sleepTs = path.resolve(here, '../../../../app/src/ui/sleep.ts');

// [name, weekday bed, weekday wake, weekend bed or null, weekend wake]
const WINDOWS = [
  ['default 23:30-07:00', 1410, 420, null, null],
  ['weekend 01:00-10:00 after weekday 22:00-06:30', 1320, 390, 60, 600],
  ['bedtime after midnight 00:30-08:00', 30, 480, null, null],
  ['weekend earlier 21:00-05:00, weekday 23:45-07:15', 1425, 435, 1260, 300],
  ['bedtime 11:45 wraps the noon rule, wake 19:00', 705, 1140, null, null],
  ['bedtime 12:00 is an evening bedtime, wake 20:00', 720, 1200, null, null],
];
// [UTC offset minutes, fixed-offset zone the app runs in]
const ZONES = [
  [0, 'UTC'],
  [120, 'Etc/GMT-2'],
  [-300, 'Etc/GMT+5'],
  [330, 'Asia/Kolkata'],
  [840, 'Pacific/Kiritimati'],
  [-720, 'Etc/GMT+12'],
];
// Thursday 2026-10-01 00:00 UTC, swept for 9 days in 15 s steps: the
// app's rounding boundary (60.5 min before bedtime) lands on a step.
const START_MS = Date.UTC(2026, 9, 1);
const STEP_MS = 15000;
const STEPS = (9 * 24 * 3600 * 1000) / STEP_MS;

const child = `
  const { judgeMode } = await import(${JSON.stringify(pathToFileURL(sleepTs).href)});
  const [bed, wake, wbed, wwake, start, step, steps] = JSON.parse(process.argv[1]);
  const w = { weekday: { bedMin: bed, wakeMin: wake },
              weekend: wbed === null ? null : { bedMin: wbed, wakeMin: wwake }, set: true };
  let last = null; const out = [];
  for (let i = 0; i < steps; i++) {
    const m = judgeMode(start + i * step, w) === 'sleep' ? 1 : 0;
    if (m !== last) { out.push([i, m]); last = m; }
  }
  process.stdout.write(JSON.stringify(out));
`;

const lines = [];
lines.push('// SPDX-License-Identifier: GPL-3.0-only');
lines.push('// Generated by gen-sleep-parity.mjs from app/src/ui/sleep.ts; do not edit.');
lines.push('#pragma once');
lines.push('');
lines.push('#include <stdint.h>');
lines.push('');
lines.push('namespace SleepParity {');
lines.push('');
lines.push(`constexpr uint64_t kStartMs = ${START_MS}ULL;`);
lines.push(`constexpr uint32_t kStepMs = ${STEP_MS};`);
lines.push(`constexpr uint32_t kSteps = ${STEPS};`);
lines.push('');
lines.push('struct Change {');
lines.push('  uint32_t step;   // first step with this mode');
lines.push('  uint8_t sleep;   // 1 = sleep, 0 = day');
lines.push('};');
lines.push('');
lines.push('struct Case {');
lines.push('  const char* name;');
lines.push('  int16_t offsetMin;');
lines.push('  uint16_t bed, wake, weekendBed, weekendWake;  // 0xFFFF = none');
lines.push('  const Change* changes;');
lines.push('  uint32_t count;');
lines.push('};');
lines.push('');
const cases = [];
let n = 0;
for (const [name, bed, wake, wbed, wwake] of WINDOWS) {
  for (const [offset, tz] of ZONES) {
    const args = JSON.stringify([bed, wake, wbed, wwake, START_MS, STEP_MS, STEPS]);
    const json = execFileSync(process.execPath, ['--no-warnings', '--input-type=module', '-e', child, args], {
      env: { ...process.env, TZ: tz },
      encoding: 'utf8',
    });
    const changes = JSON.parse(json);
    const id = `kChanges${n++}`;
    const body = changes.map(([i, m]) => `{${i}, ${m}}`).join(', ');
    lines.push(`constexpr Change ${id}[] = {${body}};`);
    cases.push(
      `    {${JSON.stringify(`${name}, UTC${offset >= 0 ? '+' : ''}${offset}`)}, ${offset}, ${bed}, ${wake}, ` +
        `${wbed ?? '0xFFFF'}, ${wwake ?? '0xFFFF'}, ${id}, ${changes.length}},`,
    );
  }
}
lines.push('');
lines.push('constexpr Case kCases[] = {');
lines.push(...cases);
lines.push('};');
lines.push('');
lines.push('}  // namespace SleepParity');
process.stdout.write(lines.join('\n') + '\n');
